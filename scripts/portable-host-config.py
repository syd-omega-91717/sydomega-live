#!/usr/bin/env python3
"""Write public/_headers and public/_redirects from vercel.json.

vercel.json stays the one source of truth for response headers and
redirects. Cloudflare Pages (and Netlify) read the same intent from two
plain files in the publish directory, so scripts/vercel-build.sh calls this
after it fills public/ and the artifact carries both forms. Vercel ignores
the two files; a host without them ignores vercel.json.

Translation (path-to-regexp source -> Pages URL pattern):
  /(.*)                     -> /*
  /(.*)\\.(js|css|...)      -> one rule per extension: /*.js, /*.css, ...
  /(a|b)(.*)                -> /a*, /b*
  /literal/path             -> /literal/path
Any other source fails the build: a rule this script cannot translate would
otherwise vanish from production without a trace.

Pages joins a header that two matching rules both set with a comma, so a
literal path that overrides a pattern's header (sw.js's Cache-Control over
the *.js one) is written with a `! Name` detach line first.

A redirect source without an extension also gets its `.html` twin, since a
Pages redirect matches the request path as sent.

Usage:
  python3 scripts/portable-host-config.py            # write into public/
  python3 scripts/portable-host-config.py --check    # translate, print, write nothing
  python3 scripts/portable-host-config.py --help
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
PUBLIC = ROOT / "public"


def patterns(source: str) -> list[str]:
    if source == "/(.*)":
        return ["/*"]
    m = re.fullmatch(r"/\(\.\*\)\\\.\(([a-z0-9|]+)\)", source)
    if m:
        return ["/*." + ext for ext in m.group(1).split("|")]
    m = re.fullmatch(r"/\(([a-z0-9|-]+)\)\(\.\*\)", source)
    if m:
        return ["/" + p + "*" for p in m.group(1).split("|")]
    if re.fullmatch(r"/[A-Za-z0-9._/-]*", source):
        return [source]
    raise ValueError(f"untranslatable header source: {source}")


def build(config: dict) -> tuple[str, str]:
    rules: list[tuple[str, list[tuple[str, str]]]] = []
    for rule in config.get("headers", []):
        pairs = [(h["key"], h["value"]) for h in rule["headers"]]
        for pat in patterns(rule["source"]):
            rules.append((pat, pairs))

    def matches(pattern: str, path: str) -> bool:
        rx = "^" + re.escape(pattern).replace(r"\*", ".*") + "$"
        return re.match(rx, path) is not None

    lines = ["# Generated by scripts/portable-host-config.py from vercel.json. Do not edit."]
    for pat, pairs in rules:
        lines.append(pat)
        if "*" not in pat:
            for key, _ in pairs:
                if any(other != pat and "*" in other and matches(other, pat)
                       and any(k.lower() == key.lower() for k, _ in opairs)
                       for other, opairs in rules):
                    lines.append(f"  ! {key}")
        for key, value in pairs:
            lines.append(f"  {key}: {value}")
    headers = "\n".join(lines) + "\n"

    out = ["# Generated by scripts/portable-host-config.py from vercel.json. Do not edit."]
    seen = set()
    for r in config.get("redirects", []):
        code = "301" if r.get("permanent", True) else "302"
        srcs = [r["source"]]
        last = r["source"].rsplit("/", 1)[-1]
        if r["source"] != "/" and "." not in last:
            srcs.append(r["source"] + ".html")
        for src in srcs:
            if src in seen or not re.fullmatch(r"/[A-Za-z0-9._/-]*", src):
                if src not in seen:
                    raise ValueError(f"untranslatable redirect source: {src}")
                continue
            seen.add(src)
            out.append(f"{src} {r['destination']} {code}")
    return headers, "\n".join(out) + "\n"


def main() -> int:
    if "--help" in sys.argv or "-h" in sys.argv:
        print(__doc__.strip())
        return 0
    config = json.loads((ROOT / "vercel.json").read_text(encoding="utf-8"))
    try:
        headers, redirects = build(config)
    except ValueError as exc:
        print(f"PORTABLE_HOST_CONFIG=FAIL {exc}")
        return 1
    rule_count = sum(1 for line in headers.splitlines() if line.startswith("/"))
    if rule_count > 100:
        print(f"PORTABLE_HOST_CONFIG=FAIL {rule_count} header rules; Cloudflare Pages allows 100")
        return 1
    if "--check" in sys.argv:
        print(headers + "\n" + redirects)
        return 0
    if not PUBLIC.is_dir():
        print("PORTABLE_HOST_CONFIG=FAIL public/ does not exist; run scripts/vercel-build.sh")
        return 1
    (PUBLIC / "_headers").write_text(headers, encoding="utf-8")
    (PUBLIC / "_redirects").write_text(redirects, encoding="utf-8")
    print(f"PORTABLE_HOST_CONFIG=PASS header_rules={rule_count} redirects={len(redirects.splitlines()) - 1}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
