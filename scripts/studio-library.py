#!/usr/bin/env python3
"""Build the Studios library payload served, owner-only, by the studio-library Edge Function.

WHY THIS EXISTS

The Studios canon (franchises, films, series, games, characters) and its written works (screenplays, episode scripts, game
design documents) lived only under docs/, which the site does not serve and the public GitHub repository exposes. The platform
had no page that could show any of it. This script derives ONE payload from the single sources (config/omega-studio-registry.json,
config/omega-studio-productions.json and the script and design files they name), so the library can never say anything the
canon does not. It writes supabase/functions/studio-library/library-data.ts, and --check fails when that file is stale.

The payload states the real status of everything (CONCEPT, SCREENPLAY_DRAFT, SCRIPTS_DRAFT, DESIGNED, PROTOTYPE) and has no field
that could claim a work is released, streaming or playable except the one game build that exists as a prototype.

USAGE
    python3 scripts/studio-library.py --write   # regenerate supabase/functions/studio-library/library-data.ts
    python3 scripts/studio-library.py --check   # exit 1 when the generated file is stale or a referenced file is missing
    python3 scripts/studio-library.py --summary # counts
"""
import argparse
import json
import pathlib
import re
import string
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
REG = ROOT / "config" / "omega-studio-registry.json"
PROD = ROOT / "config" / "omega-studio-productions.json"
OUT = ROOT / "supabase" / "functions" / "studio-library" / "library-data.ts"
HEADER = ("// GENERATED by scripts/studio-library.py --write from the Studios registry, productions and script files.\n"
          "// Do not edit by hand: scripts/studio-library.py --check and the unit tests fail when this is stale.\n")


def load(p):
    return json.loads(pathlib.Path(p).read_text(encoding="utf-8"))


def read(rel):
    p = ROOT / rel
    if not p.is_file():
        raise FileNotFoundError(rel)
    return p.read_text(encoding="utf-8")


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def build():
    reg, prod = load(REG), load(PROD)
    prods = {p["id"]: p for p in prod["productions"]}
    docs = {}
    franchises = []
    chars_by_f = {}
    for c in reg["characters"]:
        chars_by_f.setdefault(c["franchise"], []).append({"id": c["id"], "name": c["name"], "role": c["role"], "status": c["canonStatus"]})
    ages = {a["id"]: a["title"] for a in reg["ages"]}
    for f in reg["franchises"]:
        films = []
        for film in f["films"]:
            doc_ids = []
            p = prods.get(film.get("production", ""))
            if p and p.get("screenplay"):
                did = "film:%s:%s" % (f["id"], slug(film["title"]))
                docs[did] = {"kind": "screenplay", "title": film["title"], "franchise": f["id"], "status": film["status"],
                             "text": "\n\n".join(read(x).rstrip("\n") for x in p["screenplay"]) + "\n"}
                doc_ids.append(did)
            films.append({"title": film["title"], "status": film["status"], "docs": doc_ids})
        s = f["series"]
        ep_ids = []
        for path in s.get("scripts", []):
            m = re.search(r"E(\d{2})_([A-Z0-9_]+)\.fountain$", path)
            num = int(m.group(1))
            did = "episode:%s:%03d" % (f["id"], 100 + num)
            text = read(path)
            # The script's own header names the episode ("Episode: 105, "THE TRAITOR'S MEMORY""), which a filename cannot spell (no apostrophe);
            # the filename is only the fallback.
            h = re.search(r'^Episode:\s*\d+,\s*"([^"]+)"', text, re.M)
            title = string.capwords((h.group(1) if h else m.group(2).replace("_", " ")).lower())
            docs[did] = {"kind": "teleplay", "title": "%d %s" % (100 + num, title), "franchise": f["id"], "status": "SCRIPT_DRAFT_SHORT",
                         "text": text}
            ep_ids.append(did)
        g = f["game"]
        gdoc = None
        if g.get("gdd"):
            gdoc = "gdd:%s" % f["id"]
            docs[gdoc] = {"kind": "design", "title": g["title"], "franchise": f["id"], "status": g["status"], "text": read(g["gdd"])}
        build_page = g.get("build")
        franchises.append({
            "id": f["id"], "number": f["number"], "title": f["title"], "genre": f["genre"], "premise": f["premise"],
            "ages": [ages[a] for a in f["ages"]], "canonStatus": f["canonStatus"],
            "films": films,
            "series": {"title": s["title"], "seasons": s.get("seasons"), "episodesPerSeason": s.get("episodesPerSeason"),
                       "status": s.get("status", "CONCEPT"), "docs": ep_ids},
            "game": {"title": g["title"], "genre": g["genre"], "status": g["status"], "multiplayer": g["multiplayer"],
                     "doc": gdoc, "prototype": ("/" + build_page) if build_page else None,
                     "companions": [{"title": c["title"], "status": c["status"], "prototype": "/" + c["build"]} for c in g.get("companions", [])]},
            "characters": chars_by_f.get(f["id"], []),
        })
    return {
        "version": 1, "asOf": reg["asOf"], "canonVersion": reg["canonVersion"],
        "note": "Unreleased and unapproved unless a status says otherwise. A DRAFT is not a finished work; a PROTOTYPE is not a game release.",
        "franchises": franchises, "documents": docs, "status": completeness(reg),
    }


def completeness(reg):
    """What exists and what remains, from the one script that computes it (scripts/studios-presence.py), so no number is kept twice."""
    import importlib.util
    spec = importlib.util.spec_from_file_location("studios_presence", ROOT / "scripts" / "studios-presence.py")
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
    t = m.totals(reg)
    return {"films": t["films"], "filmsScripted": t["films_scripted"], "episodesDeclared": t["episodes_declared"], "episodesWritten": t["episodes_written"],
            "seriesUnsized": t["series_unsized"], "characters": t["characters"],
            "builds": [{"title": b[1], "status": b[4], "prototype": "/" + b[2]} for b in t["builds"]],
            "gamesWithoutBuild": [{"title": x[0], "status": x[1]} for x in t["games_without_build"]]}


def render(payload):
    return HEADER + "export const LIBRARY = " + json.dumps(payload, indent=1, ensure_ascii=False) + ";\n"


def rel(p):
    try:
        return str(p.relative_to(ROOT))
    except ValueError:
        return str(p)


def check():
    try:
        want = render(build())
    except FileNotFoundError as e:
        return ["referenced file does not exist: %s" % e]
    if not OUT.is_file() or OUT.read_text(encoding="utf-8") != want:
        return ["%s is stale; run scripts/studio-library.py --write" % rel(OUT)]
    return []


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--summary", action="store_true")
    a = ap.parse_args()
    if a.write:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(build()), encoding="utf-8")
        print("wrote", rel(OUT))
        return 0
    if a.summary:
        p = build()
        k = {}
        for d in p["documents"].values():
            k[d["kind"]] = k.get(d["kind"], 0) + 1
        print("franchises=%d films=%d characters=%d documents=%s words=%d" % (
            len(p["franchises"]), sum(len(f["films"]) for f in p["franchises"]), sum(len(f["characters"]) for f in p["franchises"]),
            k, sum(len(d["text"].split()) for d in p["documents"].values())))
        return 0
    errs = check()
    for e in errs:
        print("FINDING:", e)
    print("studio-library: %s" % ("OK" if not errs else "%d finding(s)" % len(errs)))
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
