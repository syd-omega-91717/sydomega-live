/* T is the merged dictionary in the original {key:{lang:string}} shape, so
   window.OmegaI18n.T keeps working for anything reading it directly. It
   starts English-only and gains a language's strings when its pack loads. */
var T={};
for(var _k in T_EN){T[_k]={en:T_EN[_k]};}

/* ── ENGINE ── */
var _lang=localStorage.getItem('omega_lang')||'en';
var _loaded={en:true};   /* packs merged into T */
var _inflight={};        /* lang -> Promise, so two rapid switches share one fetch */

function getLang(){return _lang;}

/* Fetch one language pack and merge it into T. Resolves either way: a failed
   fetch must leave the page in English rather than half-translated, matching
   the existing entry[lang]||entry['en']||key fallback chain.

   _inflight is cleared once the request settles, not kept as a permanent
   memo — memoising a REJECTED fetch would pin a member to English for the
   rest of the session after a single network blip, with re-selecting the
   language doing nothing (the resolved failure promise would be returned
   forever). Only _loaded[lang], set on success, suppresses a refetch. */
function loadPack(lang){
  if(lang==='en'||_loaded[lang])return Promise.resolve();
  if(_inflight[lang])return _inflight[lang];
  var p=fetch('/i18n/'+lang+'.json',{credentials:'omit'}).then(function(r){
    if(!r.ok)throw new Error('i18n pack '+lang+' HTTP '+r.status);
    return r.json();
  }).then(function(d){
    for(var k in d){if(!T[k])T[k]={};T[k][lang]=d[k];}
    _loaded[lang]=true;
  })['catch'](function(){/* stay on English; a later switch may retry */})
   .then(function(){delete _inflight[lang];});
  _inflight[lang]=p;
  return p;
}

/* Write txt as the element's own text WITHOUT discarding its child elements.
   The original did a flat el.textContent = txt, which replaces every child.
   Seven pages nest one data-i18n element inside another -- the topbar title
   pattern <div class="t" data-i18n="x">TITLE<small data-i18n="y">SUBTITLE
   </small></div> on analytics, approvals, feed, matrix, profile, vault, and a
   sechead on dashboard. Setting textContent on the parent deletes the
   <small>, and because querySelectorAll returns a STATIC list the subtitle is
   then "translated" while already detached, so it is simply gone. That never
   surfaced before only because translate() itself was never running (see the
   readyState note at the bottom of this file) -- fixing that race would have
   turned this latent bug into a visible one, wiping the subtitle off all
   seven pages. */
function setOwnText(el,txt){
  var i, hasElementChild=false;
  for(i=0;i<el.childNodes.length;i++){
    if(el.childNodes[i].nodeType===1){hasElementChild=true;break;}
  }
  if(!hasElementChild){el.textContent=txt;return;}
  var texts=[];
  for(i=0;i<el.childNodes.length;i++){
    if(el.childNodes[i].nodeType===3)texts.push(el.childNodes[i]);
  }
  if(texts.length){
    texts[0].nodeValue=txt;
    for(i=1;i<texts.length;i++)texts[i].nodeValue='';
  }else{
    /* authored with no own text at all (approvals.html) -- put it first, so
       it reads title-then-subtitle exactly as the markup intends */
    el.insertBefore(document.createTextNode(txt),el.firstChild);
  }
}

/* This element's own text, ignoring child elements. */
function ownText(el){
  var s='';
  for(var i=0;i<el.childNodes.length;i++){
    if(el.childNodes[i].nodeType===3)s+=el.childNodes[i].nodeValue;
  }
  return s.trim();
}

/* Apply the already-loaded dictionary to the DOM.

   IN THE BASE LANGUAGE THE MARKUP WINS. Every page here is authored in
   English, and the English dictionary entries are an older parallel copy that
   has drifted: comparing all 420 plain-text data-i18n elements against the
   dictionary found 273 identical but 106 DIFFERENT, and the dictionary is the
   worse text in most of them -- "▲ OVERVIEW" would lose its glyph and become
   "OVERVIEW", "Ω COMMAND BRIDGE" would become "Command Bridge", analytics.html
   would revert to superseded algorithm copy, and dashboard.html's
   "· 18 <span>SOVEREIGN MODULES</span>" would read "· 18 18 SOVEREIGN MODULES"
   because the dictionary entry repeats a number the markup already renders as
   a sibling node. Overwriting authored text with that would be a visible
   regression on many pages, so for the base language the dictionary only FILLS
   GAPS: it writes where the author left the text empty (41 elements, the
   deliberate "i18n supplies this" pattern -- approvals.html's topbar title is
   one) and otherwise leaves the markup alone.

   For any other language there is nothing else to show, so the dictionary is
   applied unconditionally, exactly as before. */
function apply(lang){
  var baseLang = (lang === 'en');
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key=el.getAttribute('data-i18n');
    var entry=T[key];
    if(entry){
      var txt=entry[lang]||entry['en']||key;
      if(el.tagName==='INPUT'||el.tagName==='TEXTAREA'){
        if(baseLang && (el.getAttribute('placeholder')||'').trim()) return;
        el.placeholder=txt;
      } else if(el.tagName==='IMG'){
        if(baseLang && (el.getAttribute('alt')||'').trim()) return;
        el.alt=txt;
      } else {
        if(baseLang && ownText(el)) return;
        setOwnText(el,txt);
      }
    }
  });

  /* Update lang selector buttons */
  document.querySelectorAll('[data-lang]').forEach(function(btn){
    btn.classList.toggle('on',btn.getAttribute('data-lang')===lang);
  });

  /* Dispatch event so pages can react */
  document.dispatchEvent(new CustomEvent('omega:lang',{detail:{lang:lang,dir:LANGS[lang].dir}}));
}

function translate(lang){
  lang=lang||_lang;
  if(!LANGS[lang])lang='en';
  _lang=lang;
  localStorage.setItem('omega_lang',lang);

  /* RTL / LTR — set immediately, before any fetch, so switching to Arabic
     flips direction at once instead of after a network round trip. */
  document.documentElement.setAttribute('dir',LANGS[lang].dir);
  document.documentElement.setAttribute('lang',lang);

  /* English needs no fetch: apply synchronously, exactly as before. */
  if(lang==='en'||_loaded[lang]){apply(lang);return Promise.resolve();}
  return loadPack(lang).then(function(){apply(lang);});
}

function t(key,lang){
  lang=lang||_lang;
  var e=T[key];
  return e?(e[lang]||e['en']||key):key;
}

/* Auto-translate once the DOM is ready.
   This used to register a DOMContentLoaded listener unconditionally, which
   lost a race it usually loses: bg.js injects this file by appending a
   <script> at runtime, and a dynamically inserted script is async -- the
   browser does NOT delay DOMContentLoaded for it. So on most pages this file
   finished executing AFTER that event had already fired, the listener was
   registered for something that would never happen again, and translate() was
   never called at all. Measured on a zero-latency local server, i18n.js
   landed after DOMContentLoaded on 3 of 4 sampled pages (approvals 172ms vs
   187ms, dashboard 261 vs 296, vault 137 vs 258) and only matrix.html won the
   race -- exactly the kind of intermittent behaviour that hides a bug.

   Two consequences, both real: any member whose stored language is not
   English saw no translation at all on load, and approvals.html -- the owner
   console -- rendered with a BLANK page title, because its <div class="t">
   and its subtitle <small> are empty in the markup and filled purely from
   data-i18n. Confirmed by calling OmegaI18n.translate('en') by hand in the
   console on that page: the title "INVISIBLE ARCHITECT CONSOLE" appears.

   Checking readyState first is the pattern the rest of this codebase already
   uses for exactly this reason (bg.js, omega-a11y.js, omega-cinematic.js). */
if(document.readyState==='loading'){
  document.addEventListener('DOMContentLoaded',function(){translate(_lang);});
}else{
  translate(_lang);
}

/* Expose */
window.OmegaI18n={translate:translate,t:t,getLang:getLang,LANGS:LANGS,T:T,load:loadPack};
window.omegaTranslate=translate;
